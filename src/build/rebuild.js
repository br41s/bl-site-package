import { spawn } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "../..");
const childEntry = join(__dirname, "eleventy-child.js");

let debounceTimer = null;
let building = false;
let rebuildQueued = false;

// Outcome of the last rebuild, exposed through GET /api/site/status.
//
// A failed background rebuild used to be invisible from outside: runBuild
// swallows the Eleventy error into console.error, so the site simply kept
// serving the previous _site/ and the only external symptom was "publish
// drift" — a post the API calls published that 404s on the built site.
//
// In-memory rather than a state file or a config row, because that is the
// truthful lifetime: _site/ is not in the persistent volume (see zbpack.json)
// and is regenerated by buildOnStartup() on every boot, so a build result from
// a previous process says nothing about the tree being served now. A config
// row would also be worse than useless here — setConfig() calls
// scheduleRebuild(), so recording a build would schedule another one.
let lastBuild = { at: null, ok: null };

export function getBuildState() {
  return { ...lastBuild, building };
}

// The build runs in a separate Node process, never in this one.
//
// It used to be `new Eleventy(...).write()` right here, and for a catalogue
// client that is ~14,500 product pages rendered in the server's own event
// loop: around 30s on a client's host during which the process answered no
// HTTP request at all. The Product Sheet Writer agent publishes a sheet and
// immediately reads the next one; that read landed inside the build window
// and timed out (30s), 10-23 times a day. The panel and every visitor whose
// request arrived in that window waited just the same.
//
// A child process rather than a worker thread because it is the plainer of
// the two: it is `npm run build` with an exit code, it needs nothing from the
// server process but the environment (DB_PATH, which site/_data/* opens on
// import — SQLite is in WAL mode, so the build reads while the API keeps
// writing), and an Eleventy crash or out-of-memory kills the build, not the
// site. process.execPath is whichever Node is running the server, so it is
// the same binary under Passenger on a Plesk host and under the Dockerfile on
// Zeabur. Memory: the build's transient peak is the same as it was
// in-process; what is added is only this process's resting footprint.
function runBuild() {
  building = true;
  return new Promise((resolve) => {
    let ok = true;
    let settled = false;

    // "error" (spawn itself failed) may or may not be followed by "close",
    // so both paths funnel through one idempotent finish.
    const finish = () => {
      if (settled) return;
      settled = true;
      lastBuild = { at: new Date().toISOString(), ok };
      building = false;
      resolve();
      if (rebuildQueued) {
        rebuildQueued = false;
        runBuild();
      }
    };

    const child = spawn(process.execPath, [childEntry], {
      cwd: root,
      env: process.env,
      stdio: ["ignore", "inherit", "inherit"],
    });
    child.on("error", (err) => {
      ok = false;
      console.error("[BUILD] could not start the Eleventy build:", err.message);
      finish();
    });
    child.on("close", (code, signal) => {
      if (code !== 0) {
        ok = false;
        // The child already printed the Eleventy error to our stderr.
        console.error(`[BUILD] Eleventy rebuild failed (${signal ?? `exit ${code}`})`);
      }
      finish();
    });
  });
}

// Debounces rapid successive content writes (e.g. multiple setConfig calls
// in one panel save, or a chat-agent edit session) into a single rebuild.
//
// BL_SITE_DISABLE_REBUILD=1 turns it off, for tests only. Any test that
// exercises a write path lands here 400ms later and kicks off a real Eleventy
// build of the whole catalogue — see the workaround comment in
// src/api/site.test.js, which avoids setConfig() for exactly this reason. That
// dodge stops working once the thing under test is a publish, so the escape
// hatch is explicit rather than another test tiptoeing around it. Never set
// this in a deployment: the site would stop regenerating and every panel edit
// would silently fail to appear.
export function scheduleRebuild(delayMs = 400) {
  if (process.env.BL_SITE_DISABLE_REBUILD === "1") return;
  if (debounceTimer) clearTimeout(debounceTimer);
  debounceTimer = setTimeout(() => {
    debounceTimer = null;
    if (building) rebuildQueued = true;
    else runBuild();
  }, delayMs);
}

// _site/ isn't in the persistent volume (only data/ is, see zbpack.json),
// so it's always regenerated fresh from the DB on boot.
export async function buildOnStartup() {
  await runBuild();
}
